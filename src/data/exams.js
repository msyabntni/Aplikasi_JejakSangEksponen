export function scoreMessage(score) {
  if (score >= 80) return { tone: "high", text: "Wah, bekal awalmu sudah bagus! Ayo kita buktikan kemampuanmu di hutan eksponen!" };
  if (score >= 50) return { tone: "mid", text: "Awal yang bagus! Ada beberapa jejak yang masih perlu kita pelajari bersama." };
  return { tone: "low", text: "Tidak apa-apa, penjelajah! Kita akan mulai dari dasar. Naru dan Kaciro siap menemanimu!" };
}
